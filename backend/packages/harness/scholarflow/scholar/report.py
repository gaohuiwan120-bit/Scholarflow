"""Markdown report assembly for ScholarFlow."""

from __future__ import annotations

from scholarflow.scholar.models import (
    ExperimentPlan,
    PaperEvidence,
    RepositoryEvidence,
    ResearchPlan,
    ReviewFinding,
)


def _bullet_list(items: list[str]) -> str:
    if not items:
        return "- (none)\n"
    return "".join(f"- {item}\n" for item in items)


def build_research_report(
    plan: ResearchPlan,
    papers: list[PaperEvidence],
    repositories: list[RepositoryEvidence],
    experiment: ExperimentPlan,
    reviews: list[ReviewFinding],
) -> str:
    sections = [
        f"# {plan.title}\n",
        "## Objective\n",
        plan.objective + "\n",
        "## Research Questions\n",
        _bullet_list(plan.research_questions),
        "## Key Paper Findings\n",
    ]
    if papers:
        for paper in papers[:10]:
            sections.append(f"### {paper.title}\n")
            if paper.key_findings:
                sections.append(_bullet_list(paper.key_findings))
            sections.append(f"Source: {paper.source_url}\n\n")
    else:
        sections.append("- No paper evidence collected.\n")

    sections.extend(["## Repository Landscape\n"])
    if repositories:
        for repo in repositories[:10]:
            sections.append(f"### {repo.repository}\n")
            if repo.architecture_summary:
                sections.append(repo.architecture_summary + "\n\n")
            sections.append(f"Source: {repo.source_url}\n\n")
    else:
        sections.append("- No repository evidence collected.\n")

    sections.extend(
        [
            "## Experiment Plan Summary\n",
            experiment.objective + "\n",
            "### Hypotheses\n",
            _bullet_list(experiment.hypotheses),
            "### Proposed Pipeline\n",
            _bullet_list(experiment.proposed_pipeline),
            "### Evaluation Metrics\n",
            _bullet_list(experiment.evaluation_metrics),
            "## Evidence Review\n",
        ]
    )
    if reviews:
        for finding in reviews:
            sections.append(
                f"- **{finding.status}**: {finding.claim} ({finding.reason})\n"
            )
    else:
        sections.append("- No review findings recorded.\n")

    sections.append("\n---\nGenerated by ScholarFlow.\n")
    return "".join(sections)
