"""Markdown and summary export for benchmark reports."""

from __future__ import annotations

from evaluation.scorer import BenchmarkReport, TaskScore


def render_markdown(report: BenchmarkReport) -> str:
    lines = [
        "# ScholarFlow Benchmark Report",
        "",
        f"- **Mode:** {report.mode}",
        f"- **Tasks:** {report.task_count}",
        f"- **Average score:** {report.average_score:.3f}",
        f"- **E2E pass rate:** {report.e2e_pass_rate:.1%}",
        "",
    ]
    if report.metadata:
        lines.append("## Run Metadata")
        lines.append("")
        for key, value in report.metadata.items():
            lines.append(f"- **{key}:** {value}")
        lines.append("")

    lines.extend(["## Per-Task Results", ""])
    lines.append("| Task | Score | E2E Pass | Top Metrics |")
    lines.append("|------|-------|----------|-------------|")
    for result in report.results:
        top = _top_metrics(result, limit=4)
        top_str = ", ".join(f"{n}={s:.2f}" for n, s in top)
        lines.append(f"| {result.task_id} | {result.score:.3f} | {'✅' if result.e2e_pass else '❌'} | {top_str} |")

    lines.extend(["", "## Metric Definitions (Resume)", ""])
    lines.append("| Metric | Meaning |")
    lines.append("|--------|---------|")
    definitions = [
        ("artifact_completeness", "9 类产物是否齐全"),
        ("schema_validity", "JSON 是否通过 Pydantic 校验"),
        ("topic_relevance", "产物文本是否包含主题关键词"),
        ("url_validity", "paper/repo 来源 URL 是否合法"),
        ("evidence_coverage", "论文/仓库数量是否达标"),
        ("e2e_pass_gate", "关键指标硬门槛（完整性+Schema+URL+相关性）"),
    ]
    for name, meaning in definitions:
        lines.append(f"| {name} | {meaning} |")

    lines.extend(["", "## Detailed Breakdown", ""])
    for result in report.results:
        lines.append(f"### {result.task_id}")
        lines.append("")
        lines.append(f"- Prompt: {result.prompt}")
        lines.append(f"- Score: {result.score:.3f}")
        lines.append(f"- E2E pass: {result.e2e_pass}")
        lines.append("")
        lines.append("| Metric | Score |")
        lines.append("|--------|-------|")
        for metric in result.metrics:
            lines.append(f"| {metric.name} | {metric.score:.3f} |")
        lines.append("")

    lines.append("---")
    lines.append("Generated by ScholarFlow evaluation harness.")
    return "\n".join(lines)


def resume_bullet_summary(report: BenchmarkReport) -> str:
    return (
        f"ScholarFlow E2E benchmark: {report.task_count} tasks, "
        f"avg score {report.average_score:.2f}, E2E pass rate {report.e2e_pass_rate:.0%} "
        f"({sum(1 for r in report.results if r.e2e_pass)}/{report.task_count} passed hard gates)."
    )


def _top_metrics(result: TaskScore, limit: int = 4) -> list[tuple[str, float]]:
    ranked = sorted(result.metrics, key=lambda m: m.score, reverse=True)
    return [(m.name, m.score) for m in ranked[:limit]]
